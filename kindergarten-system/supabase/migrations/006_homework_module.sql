-- ─── Per-student Homework Submissions ───────────────────────────────────────
CREATE TABLE IF NOT EXISTS assignment_submissions (
  id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  assignment_id    INTEGER NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
  student_id       INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  status           TEXT NOT NULL DEFAULT 'assigned',
  submitted_at     TIMESTAMPTZ,
  parent_note      TEXT,
  attachment_url   TEXT,
  teacher_feedback TEXT,
  score            NUMERIC(5,2),
  reviewed_by      UUID REFERENCES users(id) ON DELETE SET NULL,
  reviewed_at      TIMESTAMPTZ,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (assignment_id, student_id),
  CHECK (score IS NULL OR (score >= 0 AND score <= 10))
);

-- Create assigned rows for existing published assignments and active class
-- enrolments. Conflict handling makes this safe to rerun.
INSERT INTO assignment_submissions (assignment_id, student_id, status)
SELECT assignment_record.id, student_class.student_id, 'assigned'
FROM assignments assignment_record
JOIN student_classes student_class ON student_class.class_id = assignment_record.class_id
WHERE assignment_record.status = 'published'
  AND (student_class.start_date IS NULL OR student_class.start_date <= assignment_record.assigned_date)
  AND (student_class.end_date IS NULL OR student_class.end_date >= assignment_record.assigned_date)
ON CONFLICT (assignment_id, student_id) DO NOTHING;

-- ─── Indexes and Updated-at Triggers ────────────────────────────────────────
CREATE INDEX IF NOT EXISTS idx_assignments_branch ON assignments(branch_id);
