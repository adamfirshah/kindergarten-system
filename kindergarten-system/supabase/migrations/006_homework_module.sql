-- PAPA Kindergarten System — Homework module
-- Reuses the existing assignments table and adds a separate submission table
-- because one assignment can have one submission per student.
-- Run after 005_finance_module.sql.

-- Keep compatibility with projects where the original assignments table has
-- not yet been created. Existing tables are preserved and extended below.
CREATE TABLE IF NOT EXISTS assignments (
  id                     SERIAL PRIMARY KEY,
  assignment_description TEXT,
  class_id               INTEGER REFERENCES classes(id) ON DELETE CASCADE,
  created_at             TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ─── Extend Existing Assignments ────────────────────────────────────────────
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS id INTEGER GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS assignment_description TEXT;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS class_id INTEGER REFERENCES classes(id) ON DELETE CASCADE;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS branch_id UUID REFERENCES branches(id) ON DELETE SET NULL;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS title TEXT;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS subject TEXT;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS instructions TEXT;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS assigned_date DATE;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS due_date DATE;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS status TEXT;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS attachment_url TEXT;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS created_by UUID REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT now();
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT now();

CREATE UNIQUE INDEX IF NOT EXISTS idx_assignments_compat_id ON assignments(id);

UPDATE assignments
SET
  title = COALESCE(title, assignment_description, 'Assignment ' || id::TEXT),
  instructions = COALESCE(instructions, assignment_description, ''),
  subject = COALESCE(subject, 'General'),
  assigned_date = COALESCE(assigned_date, created_at::DATE, CURRENT_DATE),
  due_date = COALESCE(due_date, created_at::DATE + 7, CURRENT_DATE + 7),
  status = COALESCE(status, 'published');

UPDATE assignments assignment_record
SET branch_id = class_record.branch_id
FROM classes class_record
WHERE class_record.id = assignment_record.class_id
  AND assignment_record.branch_id IS NULL;

