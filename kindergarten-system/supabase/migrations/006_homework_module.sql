  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ─── Row-Level Security: Assignments ────────────────────────────────────────
ALTER TABLE assignments ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "assignments_select_by_role" ON assignments;
DROP POLICY IF EXISTS "assignments_manage_by_staff" ON assignments;

CREATE POLICY "assignments_select_by_role" ON assignments FOR SELECT TO authenticated
  USING (
    auth_user_role() = 1
    OR (auth_user_role() IN (2, 3) AND branch_id = auth_user_branch())
    OR (
      auth_user_role() = 4
      AND status = 'published'
      AND EXISTS (
        SELECT 1
        FROM student_classes student_class
        JOIN student_parents student_parent ON student_parent.student_id = student_class.student_id
        JOIN parents parent_record ON parent_record.id = student_parent.parent_id
        WHERE student_class.class_id = assignments.class_id
          AND parent_record.user_id = auth.uid()
      )
    )
  );

CREATE POLICY "assignments_manage_by_staff" ON assignments FOR ALL TO authenticated
  USING (
    auth_user_role() IN (1, 2, 3)
    AND (auth_user_role() = 1 OR branch_id = auth_user_branch())
  )
  WITH CHECK (
    auth_user_role() IN (1, 2, 3)
    AND (auth_user_role() = 1 OR branch_id = auth_user_branch())
  );

-- ─── Row-Level Security: Submissions ────────────────────────────────────────
ALTER TABLE assignment_submissions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "submissions_select_by_role" ON assignment_submissions;
DROP POLICY IF EXISTS "submissions_insert_by_role" ON assignment_submissions;
DROP POLICY IF EXISTS "submissions_update_by_role" ON assignment_submissions;

CREATE POLICY "submissions_select_by_role" ON assignment_submissions FOR SELECT TO authenticated
  USING (
    auth_user_role() = 1
    OR EXISTS (
      SELECT 1 FROM assignments assignment_record
      WHERE assignment_record.id = assignment_submissions.assignment_id
        AND auth_user_role() IN (2, 3)
        AND assignment_record.branch_id = auth_user_branch()
    )
    OR EXISTS (
      SELECT 1
      FROM student_parents student_parent
      JOIN parents parent_record ON parent_record.id = student_parent.parent_id
      WHERE student_parent.student_id = assignment_submissions.student_id
        AND auth_user_role() = 4
        AND parent_record.user_id = auth.uid()
    )
  );

CREATE POLICY "submissions_insert_by_role" ON assignment_submissions FOR INSERT TO authenticated
  WITH CHECK (
    auth_user_role() = 1
    OR EXISTS (
      SELECT 1 FROM assignments assignment_record
      WHERE assignment_record.id = assignment_submissions.assignment_id
        AND auth_user_role() IN (2, 3)
        AND assignment_record.branch_id = auth_user_branch()
    )
    OR (
      auth_user_role() = 4
      AND status = 'submitted'
      AND EXISTS (
        SELECT 1
        FROM student_parents student_parent
        JOIN parents parent_record ON parent_record.id = student_parent.parent_id
        WHERE student_parent.student_id = assignment_submissions.student_id
          AND parent_record.user_id = auth.uid()
      )
      AND EXISTS (
        SELECT 1
        FROM assignments assignment_record
        JOIN student_classes student_class
          ON student_class.class_id = assignment_record.class_id
        WHERE assignment_record.id = assignment_submissions.assignment_id
          AND student_class.student_id = assignment_submissions.student_id
          AND assignment_record.status = 'published'
      )
    )
  );

CREATE POLICY "submissions_update_by_role" ON assignment_submissions FOR UPDATE TO authenticated
  USING (
    auth_user_role() = 1
    OR EXISTS (
      SELECT 1 FROM assignments assignment_record
      WHERE assignment_record.id = assignment_submissions.assignment_id
        AND auth_user_role() IN (2, 3)
        AND assignment_record.branch_id = auth_user_branch()
    )
    OR EXISTS (
      SELECT 1
      FROM student_parents student_parent
      JOIN parents parent_record ON parent_record.id = student_parent.parent_id
      WHERE student_parent.student_id = assignment_submissions.student_id
        AND auth_user_role() = 4
        AND parent_record.user_id = auth.uid()
        AND assignment_submissions.status IN ('assigned', 'submitted', 'late')
    )
  )
  WITH CHECK (
    auth_user_role() = 1
    OR EXISTS (
      SELECT 1 FROM assignments assignment_record
      WHERE assignment_record.id = assignment_submissions.assignment_id
        AND auth_user_role() IN (2, 3)
        AND assignment_record.branch_id = auth_user_branch()
    )
    OR (
      auth_user_role() = 4
      AND status = 'submitted'
      AND EXISTS (
        SELECT 1
        FROM student_parents student_parent
        JOIN parents parent_record ON parent_record.id = student_parent.parent_id
        WHERE student_parent.student_id = assignment_submissions.student_id
          AND parent_record.user_id = auth.uid()
      )
      AND EXISTS (
        SELECT 1
        FROM assignments assignment_record
        JOIN student_classes student_class
          ON student_class.class_id = assignment_record.class_id
        WHERE assignment_record.id = assignment_submissions.assignment_id
          AND student_class.student_id = assignment_submissions.student_id
          AND assignment_record.status = 'published'
      )
    )
  );
